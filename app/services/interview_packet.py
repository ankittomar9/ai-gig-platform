from typing import Dict, Any, List
from app.database import get_job_by_id, get_user_profile
from app.services.humanizer import clean_ai_cliches

def generate_interview_packet(job_id: str, profile: Dict[str, Any]) -> Dict[str, Any]:
    job = get_job_by_id(job_id)
    if not job:
        raise ValueError(f"Job {job_id} not found")

    title = job.get("title", "AI Specialist")
    company = job.get("company", "Company")
    category = job.get("category", "Generalist")
    tier = job.get("tier", "Mid-Tier ($15-$30)")
    candidate_name = profile.get("name", "Ankit Singh Tomar")
    candidate_skills = profile.get("skills", ["Java", "Spring Boot", "SQL", "Docker", "GCP", "Linux", "API"])
    skills_str = ", ".join(candidate_skills[:5])

    # 1. Company Evaluation Dossier & Rubric Expectations
    if "Cohere" in company or "Data Infrastructure" in title or "Systems" in title:
        company_focus = f"{company} focuses heavily on enterprise-grade foundation models and robust post-training data infrastructure. They test data cleanliness, pipeline reliability, deduplication, and system uptime."
        q1 = "Introduce yourself and explain your backend/data infrastructure background. How have you built or maintained resilient pipelines?"
        ans1 = f"I'm {candidate_name}. Over the past few years, I've specialized in backend engineering and production systems using {skills_str}. My core focus is building resilient services—handling high-concurrency requests, monitoring service health on GCP/Linux, and ensuring data pipelines don't drop messages or silently corrupt state during incident spikes."
        
        q2 = "In a post-training data pipeline handling millions of instruction-tuning pairs, how would you design a validation filter to catch corrupted tokens or malformed JSONL records without tanking throughput?"
        ans2 = "I'd use a streaming validator using schema verification (like Pydantic or FastJSON) at the ingestion boundary rather than loading whole batches into memory. I'd set up dead-letter queues for unparseable records so the pipeline doesn't crash, and emit metrics for error rates to catch data drifts early."
        
        q3 = "When preparing training datasets, how do you handle deduplication and synthetic dataset contamination?"
        ans3 = "I apply MinHash with LSH (Locality Sensitive Hashing) for fuzzy near-deduplication to prevent the model from memorizing identical phrasings. For contamination, I cross-reference evaluation benchmark splits against training corpora using strict n-gram matching."
        
        q4 = "A data pipeline node crashes halfway through an 8-hour preprocessing job. How do you design your jobs to be idempotent and recoverable?"
        ans4 = "Every batch step must be atomic and state-checkpointed. By storing watermarks or processed batch UUIDs in a persistent datastore, a restarted worker simply resumes from the last confirmed watermark without reprocessing or duplicating records."

    elif category == "Coding" or "Software" in title:
        company_focus = f"{company} evaluates algorithmic correctness, clean code readability, edge-case coverage, and clear verbal communication during debugging."
        q1 = "Walk me through your background in software engineering and backend development."
        ans1 = f"I'm a backend software engineer with hands-on experience building services in {skills_str}. In my daily work, I focus on clean code design, API stability, and writing automated tests to guarantee zero regressions in production."
        
        q2 = "Suppose a model produces an O(N^2) solution for an array search or substring problem. How do you critique it and guide it to O(N) or O(N log N)?"
        ans2 = "I start by pointing out the nested loop bottleneck and calculating the worst-case space and time complexity. Then I suggest using a hash map or two-pointer sliding window approach to achieve linear time, and outline specific test cases (e.g., duplicate elements, empty arrays) to verify the optimization."
        
        q3 = "What is your approach to reviewing code generated by an AI model to detect hidden bugs?"
        ans3 = "I don't just read code passively; I dry-run execution branches with boundary inputs: nulls, zero, off-by-one indices, and large collections. I also verify that external library calls aren't hallucinated and that exception handling doesn't swallow critical errors."
        
        q4 = "How do you handle ambiguous requirements when writing code or creating reference solutions?"
        ans4 = "I state my assumptions explicitly in documentation before writing implementation code, write unit tests confirming both edge cases, and flag where specification constraints conflict."

    elif category == "Writing & RLHF" or "Trainer" in title or "Evaluator" in title:
        company_focus = f"{company} tests strict guideline adherence, pairwise ranking justifications, and adversarial hallucination detection."
        q1 = "Why are you interested in RLHF and AI training, and what makes you detail-oriented?"
        ans1 = f"I'm drawn to AI training because model quality depends entirely on clean ground-truth human data. With my technical background in {skills_str}, I bring structured discipline—reading rubrics carefully, checking technical claims, and catching subtle model hallucinations."
        
        q2 = "Model A is technically accurate but verbose and jargon-heavy. Model B is concise and easy to understand but misses one small constraint. Which do you rank higher and why?"
        ans2 = "If the prompt specified brevity or a non-technical audience, Model B aligns better with user intent, though its omission must be penalized. If the prompt demanded comprehensive technical completeness, Model A wins. I always ground my ranking in whether the prompt's hard constraints were respected."
        
        q3 = "How do you spot and document subtle factual hallucinations in AI responses?"
        ans3 = "I independently verify every factual assertion—dates, API parameter names, math calculations—using trusted external sources. When documenting, I quote the exact hallucinated sentence and provide the factual correction."
        
        q4 = "How do you handle ambiguous evaluation guidelines that contradict each other?"
        ans4 = "I refer back to the core project hierarchy (typically: Safety/Truthfulness > Instruction Following > Formatting/Tone). I document the ambiguity in my reviewer notes so project leads can calibrate the rubric."

    else: # Microtask & General
        company_focus = f"{company} values accuracy benchmarks (>98%), rapid turnaround time, and strict adherence to project rubrics without guesswork."
        q1 = "What experience do you have with structured data evaluation and quality assurance?"
        ans1 = f"I have a reliable technical background in {skills_str} and a strong focus on precision. I am accustomed to following detailed technical documentation and maintaining high accuracy under tight deadlines."
        
        q2 = "How do you maintain high quality when performing repetitive evaluation tasks over several hours?"
        ans2 = "I maintain a consistent evaluation checklist for every task: verify inputs, check guidelines, confirm grading criteria, and self-audit before submitting. I take short scheduled breaks to avoid fatigue-induced errors."
        
        q3 = "What do you do if a task guidelines document doesn't cover a confusing edge case?"
        ans3 = "I do not guess. I review precedent examples in the project guidelines, check the project FAQ, and if still unresolved, flag the item with an explanatory note according to project protocol."
        
        q4 = "How do you ensure data confidentiality and platform security?"
        ans4 = "I maintain a secure, private workstation, never copy confidential project data to public tools, and strictly adhere to non-disclosure agreements."

    # Compile the Full Ready-to-Practice Packet
    packet_markdown = f"""==================================================
INTERVIEW PACKET: {title} at {company}
Prepared for: {candidate_name}
Target Tier: {tier} | Domain: {category}
==================================================

--------------------------------------------------
1. COMPANY PROFILE & EVALUATION FOCUS
--------------------------------------------------
{company_focus}

--------------------------------------------------
2. TOP PREDICTED INTERVIEW QUESTIONS & WINNING ANSWERS
--------------------------------------------------

[Question 1: Background & Screening]
{q1}

[Winning Answer Formulation]
"{ans1}"

---

[Question 2: Core Technical & Domain Competency]
{q2}

[Winning Answer Formulation]
"{ans2}"

---

[Question 3: Quality Control & Methodology]
{q3}

[Winning Answer Formulation]
"{ans3}"

---

[Question 4: Edge Cases, Resilience & Adversarial Scenarios]
{q4}

[Winning Answer Formulation]
"{ans4}"

--------------------------------------------------
3. KEY RED FLAGS TO AVOID IN THIS INTERVIEW
--------------------------------------------------
❌ DO NOT give generic 1-sentence answers. AI evaluators grade depth and structured reasoning.
❌ DO NOT pretend to know an answer if unsure. Instead, explain your debugging/verification process.
❌ DO NOT skip edge cases. Always mention inputs like nulls, empty payloads, or contradictory constraints.
✅ DO speak with clear first-person technical ownership ("I monitored...", "I verified...", "I tested...").
✅ DO tie your answers back to {company}'s goal of training reliable, high-integrity AI models.
==================================================
"""

    return {
        "job_id": job_id,
        "company": company,
        "role_title": title,
        "category": category,
        "tier": tier,
        "company_focus": company_focus,
        "questions_and_answers": [
            {"round": "Round 1: Screening", "question": q1, "winning_answer": clean_ai_cliches(ans1)},
            {"round": "Round 2: Domain Deep-Dive", "question": q2, "winning_answer": clean_ai_cliches(ans2)},
            {"round": "Round 3: Quality & Evaluation", "question": q3, "winning_answer": clean_ai_cliches(ans3)},
            {"round": "Round 4: Edge Cases & Scenarios", "question": q4, "winning_answer": clean_ai_cliches(ans4)}
        ],
        "full_packet_text": clean_ai_cliches(packet_markdown)
    }
